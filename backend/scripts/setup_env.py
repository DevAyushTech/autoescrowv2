"""Fill a blank AUTOESCROW_JWT_SECRET in the root .env without overwriting it."""

import re
import secrets
from pathlib import Path

ENV_PATH = Path(__file__).resolve().parents[2] / ".env"
SECRET_LINE = re.compile(r"^AUTOESCROW_JWT_SECRET=(\S*)", re.MULTILINE)


def main() -> None:
    if not ENV_PATH.exists():
        raise SystemExit("Missing .env. Run `make env` or copy .env.example first.")

    text = ENV_PATH.read_text()
    match = SECRET_LINE.search(text)
    if match is not None and match.group(1):
        print("AUTOESCROW_JWT_SECRET is already set")
        return

    if match is None:
        updated = text.rstrip("\n") + (
            "\n\n# Generated by `make env`; never commit this value.\n"
            f"AUTOESCROW_JWT_SECRET={secrets.token_urlsafe(48)}\n"
        )
    else:
        updated = SECRET_LINE.sub(
            f"AUTOESCROW_JWT_SECRET={secrets.token_urlsafe(48)}",
            text,
            count=1,
        )

    ENV_PATH.write_text(updated)
    print("Generated AUTOESCROW_JWT_SECRET in .env")


if __name__ == "__main__":
    main()
